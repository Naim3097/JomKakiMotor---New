/** Glyph in the brand-tinted circle used by feature grids. */
export function IconBadge({
  name,
  size = "md",
  onDark = false,
}: {
  name: LineIconName;
  size?: "sm" | "md";
  onDark?: boolean;
}) {
  const box = size === "sm" ? "h-10 w-10" : "h-12 w-12";
  const glyph = size === "sm" ? "h-5 w-5" : "h-6 w-6";
  return (
    <span
      className={`flex ${box} shrink-0 items-center justify-center rounded-full ${
        onDark ? "bg-white/10 text-brand" : "bg-brand/10 text-brand"
      }`}
    >
      <LineIcon name={name} className={glyph} />
    </span>
  );
}
